// blargg's ntsc filter as two gpu passes, ported to raylib's glsl 3.30 from the
// libretro glsl-shaders collection (ntsc/shaders/blargg/blargg-0.glsl and blargg-1.glsl,
// https://github.com/libretro/glsl-shaders), which follows the kernel design of
// shay green's (blargg's) nes_ntsc. the source files carry no license header of their own.
//
// pass 0 turns each pixel into a composite signal; pass 1 decodes it with a sinc style
// luma filter and a gaussian chroma filter, with blargg's sharpness, resolution,
// fringing, artifact and bleed controls. the libretro preset runs them on the frame
// stretched to 640 pixels wide, which this follows.

static const char* ntsc_pass0_source =
"#version 330\n"
"in vec2 fragTexCoord;\n"
"uniform sampler2D texture0;\n"
"uniform vec2 TextureSize;\n"
"uniform float FrameCount;\n"
"uniform float ntsc_bri;\n"
"uniform float ntsc_hue;\n"
"uniform float stat_ph;\n"
"uniform float pi_mod;\n"
"uniform float vert_scal;\n"
"out vec4 finalColor;\n"
"#define PI 3.1415926\n"
"const mat3 RGBYIQ = mat3(\n"
"	0.2989, 0.5870, 0.1140,\n"
"	0.5959, -0.2744, -0.3216,\n"
"	0.2115, -0.5229, 0.3114);\n"
"#define onedeg 0.017453\n"
"void main()\n"
"{\n"
"	float modulo = 3.0;\n"
"	float phase = floor(fragTexCoord.x * TextureSize.x) * pi_mod * onedeg + mod(floor(fragTexCoord.y * TextureSize.y), modulo) * PI * vert_scal;\n"
"	phase += ntsc_hue;\n"
"	if (stat_ph == 1.0) phase += sin(mod(FrameCount, 2.0)) * PI;\n"
"	vec3 YUV = texture(texture0, fragTexCoord).rgb;\n"
"	YUV = YUV * RGBYIQ;\n"
"	YUV *= vec3(ntsc_bri, cos(phase), sin(phase));\n"
"	float signal = YUV.x + YUV.y + YUV.z;\n"
"	finalColor = vec4(vec3(signal), 1.0);\n"
"}\n";

static const char* ntsc_pass1_source =
"#version 330\n"
"in vec2 fragTexCoord;\n"
"uniform sampler2D texture0;\n"
"uniform vec2 TextureSize;\n"
"uniform float FrameCount;\n"
"uniform float ntsc_sat;\n"
"uniform float ntsc_bleed;\n"
"uniform float ntsc_res;\n"
"uniform float ntsc_sharp;\n"
"uniform float LUMA_CUTOFF;\n"
"uniform float stat_ph;\n"
"uniform float fring;\n"
"uniform float afacts;\n"
"uniform float kernel_half;\n"
"uniform float pi_mod;\n"
"uniform float vert_scal;\n"
"out vec4 finalColor;\n"
"#define PI 3.1415926\n"
"#define fringing_mid 0.8\n"
"#define fringing_max 1.6\n"
"#define artifacts_mid 0.4\n"
"#define artifacts_max 0.6\n"
"#define onedeg 0.017453\n"
"const mat3 YIQ2RGB = mat3(\n"
"	1.0, 0.956, 0.6210,\n"
"	1.0, -0.2720, -0.6474,\n"
"	1.0, -1.1060, 1.7046);\n"
"float blackman(float x)\n"
"{\n"
"	return 0.42 - 0.5 * cos(x) + 0.08 * cos(x * 2.0);\n"
"}\n"
"void main()\n"
"{\n"
"	vec2 size = TextureSize;\n"
"	vec2 uv = fragTexCoord;\n"
"	int i = int(kernel_half);\n"
"	float cutoff_factor = -0.03125;\n"
"	float cutoff = ntsc_bleed;\n"
"	if (cutoff < 0.0) {\n"
"		// keep extreme value accessible only near upper end of scale (1.0)\n"
"		cutoff *= cutoff;\n"
"		cutoff *= cutoff;\n"
"		cutoff *= cutoff;\n"
"		cutoff *= -30.0 / 0.65;\n"
"	}\n"
"	cutoff = cutoff_factor - 0.65 * cutoff_factor * cutoff;\n"
"	// sample the composite signal and decode to yuv\n"
"	vec3 YUV = vec3(0);\n"
"	float sum = 0.0;\n"
"	float to_angle = ntsc_res + 1.0;\n"
"	float rolloff = 1.0 + ntsc_sharp * 0.032;\n"
"	float maxh = kernel_half * 2.0;\n"
"	float pow_a_n = pow(rolloff, maxh);\n"
"	to_angle = PI / maxh * LUMA_CUTOFF * (to_angle * to_angle + 1.0);\n"
"	// luma: blargg's sinc style kernel\n"
"	for (int n = 0; n < i * 2 + 1; n++) {\n"
"		float a = PI * 2.0 / (kernel_half * 2.0) * float(n);\n"
"		float w = blackman(a);\n"
"		vec2 pos = uv - vec2(kernel_half / size.x, 0.0) + vec2(float(n) / size.x, 0.0);\n"
"		float x = float(n) - kernel_half;\n"
"		float angle = x * to_angle;\n"
"		float kernel = 0.0;\n"
"		float fringing = 0.0;\n"
"		if (fract(float(n + 2) / 4.0) == 0.0) {\n"
"			if (fring > 0.0)\n"
"				fringing = -fring * (fringing_max - fringing_mid);\n"
"		}\n"
"		// instability occurs at center point with rolloff very close to 1.0\n"
"		if (x > 1.056 || pow_a_n > 1.056 || pow_a_n < 0.981) {\n"
"			float rolloff_cos_a = rolloff * cos(angle);\n"
"			float num = 1.0 - rolloff_cos_a - pow_a_n * cos(maxh * angle) + pow_a_n * rolloff * cos((maxh - 1.0) * angle);\n"
"			float den = 1.0 - rolloff_cos_a - rolloff_cos_a + rolloff * rolloff;\n"
"			float dsf = num / den;\n"
"			kernel = dsf - 0.5;\n"
"		}\n"
"		YUV.x += texture(texture0, pos).r * w * kernel * (1.0 + fringing);\n"
"		sum += w * kernel;\n"
"	}\n"
"	YUV.x /= sum;\n"
"	float sumc = 0.0;\n"
"	// chroma: blargg's gaussian kernel\n"
"	for (int n = -i; n < i; n++) {\n"
"		vec2 pos = uv + vec2(float(n) / size.x, 0.0);\n"
"		float modulo = 3.0;\n"
"		float phase = (floor(fragTexCoord.x * size.x) + float(n)) * pi_mod * onedeg + mod(floor(fragTexCoord.y * size.y), modulo) * PI * vert_scal;\n"
"		if (stat_ph == 1.0) phase += sin(mod(FrameCount, 2.0)) * PI;\n"
"		float r = exp(cutoff * float(n) * float(n));\n"
"		float artifacts = 0.0;\n"
"		if (fract(float(n + i + 2) / 4.0) == 0.0) {\n"
"			if (afacts > 0.0)\n"
"				artifacts = -afacts * (artifacts_max - artifacts_mid);\n"
"		}\n"
"		vec2 carrier = ntsc_sat * vec2(cos(phase), sin(phase));\n"
"		YUV.yz += r * texture(texture0, pos).gb * carrier * (1.0 + artifacts);\n"
"		sumc += r;\n"
"	}\n"
"	YUV.yz /= sumc;\n"
"	// back to rgb\n"
"	YUV = YUV * YIQ2RGB;\n"
"	finalColor = vec4(YUV, 1.0);\n"
"}\n";
